"""Generates src/geo_dots.rs: land points (latitude, longitude) for the rotating dot globe,
on a near-equal-area grid (rows STEP degrees apart, columns widened toward the poles).

Land is sampled from NASA's Blue Marble (public domain) as shipped by fframes-components
(media/blue-marble-z4.jpg, Web Mercator, 4096x4096). Needs ffmpeg on PATH.
Run: py tools/geo-dots.py
"""
import glob
import math
import os
import pathlib
import shutil
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
STEP = 2.6  # degrees between rows, and between columns on the equator
NORTH, SOUTH = 80.0, -58.0
SIZE = 1024


def mercator_v(lat):
    return (180 - 180 / math.pi * math.log(math.tan(math.pi / 4 + lat * math.pi / 360))) / 360


def main():
    ffmpeg = shutil.which('ffmpeg')
    home = os.environ.get('CARGO_HOME', os.path.expanduser('~/.cargo'))
    marble = sorted(glob.glob(f'{home}/registry/src/*/fframes-components-0.1.2/media/blue-marble-z4.jpg'))
    if not ffmpeg or not marble:
        sys.exit('needs ffmpeg on PATH and the fframes-components 0.1.2 sources (cargo fetch)')
    raw = subprocess.run([ffmpeg, '-v', 'error', '-i', marble[0], '-vf', f'scale={SIZE}:{SIZE}',
                          '-f', 'rawvideo', '-pix_fmt', 'rgb24', '-'], check=True, capture_output=True).stdout
    points = []
    lat = NORTH
    while lat >= SOUTH:
        columns = max(1, round(360 / STEP * math.cos(math.radians(lat))))
        for c in range(columns):
            lon = -180 + (c + 0.5) * 360 / columns
            u = (lon + 180) / 360
            v = mercator_v(lat)
            i = (min(int(v * SIZE), SIZE - 1) * SIZE + min(int(u * SIZE), SIZE - 1)) * 3
            r, g, b = raw[i], raw[i + 1], raw[i + 2]
            ocean = b > r * 1.2 and b >= g * 0.95 and r + g + b < 330
            if not ocean:
                points.append(f'({lat:.1f}, {lon:.1f})')
        lat -= STEP
    rows = ',\n'.join('    ' + ', '.join(points[i:i + 8]) for i in range(0, len(points), 8))
    source = f'''//! Generated by tools/geo-dots.py from NASA Blue Marble; do not edit by hand.

/// Land points (latitude, longitude) in degrees, about {STEP} degrees apart.
pub const LAND: [(f32, f32); {len(points)}] = [
{rows},
];
'''
    (ROOT / 'src' / 'geo_dots.rs').write_text(source, encoding='utf-8')
    print(f'{len(points)} land points')


if __name__ == '__main__':
    main()
